-- KAYUK BET: additive migration for the EXISTING production database.
-- Safe to run before enabling slots: creates only slot history + RPC.
-- It does not reset, delete, or seed existing profiles, balances, bets, or transactions.
-- Keep FOOTBALL_SLOTS_ENABLED unset/false until the production schema is verified.

create extension if not exists pgcrypto;

create table if not exists public.slot_spins (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  stake bigint not null check (stake >= 10 and stake <= 100000),
  symbols text[] not null,
  payout bigint not null default 0 check (payout >= 0),
  jackpot boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists slot_spins_user_id_idx on public.slot_spins(user_id);
create index if not exists slot_spins_created_at_idx on public.slot_spins(created_at desc);

create or replace function public.spin_football_slots(p_user_id uuid, p_stake bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_balance bigint;
  v_roll integer;
  v_symbols text[];
  v_payout bigint := 0;
  v_jackpot boolean := false;
begin
  if p_stake is null or p_stake < 10 or p_stake > 100000 then
    raise exception 'Invalid stake';
  end if;

  select balance into v_balance
  from public.balances
  where user_id = p_user_id
  for update;

  if not found or v_balance < p_stake then
    raise exception 'Insufficient balance';
  end if;

  update public.balances
  set balance = balance - p_stake, updated_at = now()
  where user_id = p_user_id
  returning balance into v_balance;

  insert into public.transactions(user_id, amount, type, note)
  values (p_user_id, -p_stake, 'bet_placed', 'Ставка в слотах КАЮК BET');

  v_roll := floor(random() * 100000)::integer + 1;

  if v_roll = 1 then
    v_symbols := array['👑','👑','👑']; v_payout := p_stake * 500; v_jackpot := true;
  elsif v_roll <= 1000 then
    v_symbols := array['💎','💎','💎']; v_payout := p_stake * 20;
  elsif v_roll <= 3000 then
    v_symbols := array['⭐','⭐','⭐']; v_payout := p_stake * 10;
  elsif v_roll <= 7000 then
    v_symbols := array['🍒','🍒','🍒']; v_payout := p_stake * 5;
  elsif v_roll <= 22000 then
    case floor(random() * 4)::integer
      when 0 then v_symbols := array['🍒','🍒','🍋'];
      when 1 then v_symbols := array['🍋','⭐','🍋'];
      when 2 then v_symbols := array['💎','💎','🍋'];
      else v_symbols := array['⭐','🍋','⭐'];
    end case;
    v_payout := p_stake * 2;
  else
    case floor(random() * 5)::integer
      when 0 then v_symbols := array['🍒','🍋','⭐'];
      when 1 then v_symbols := array['🍋','💎','🍒'];
      when 2 then v_symbols := array['⭐','🍒','💎'];
      when 3 then v_symbols := array['💎','⭐','🍋'];
      else v_symbols := array['🍋','🍒','💎'];
    end case;
  end if;

  if v_payout > 0 then
    update public.balances
    set balance = balance + v_payout, updated_at = now()
    where user_id = p_user_id
    returning balance into v_balance;

    insert into public.transactions(user_id, amount, type, note)
    values (
      p_user_id,
      v_payout,
      'bet_won',
      case when v_jackpot then 'ДЖЕКПОТ в слотах КАЮК BET ×500'
           else 'Выигрыш в слотах КАЮК BET' end
    );
  end if;

  insert into public.slot_spins(user_id, stake, symbols, payout, jackpot)
  values (p_user_id, p_stake, v_symbols, v_payout, v_jackpot);

  return jsonb_build_object(
    'stake', p_stake,
    'symbols', to_jsonb(v_symbols),
    'payout', v_payout,
    'jackpot', v_jackpot,
    'balance', v_balance
  );
end;
$$;

revoke all on function public.spin_football_slots(uuid, bigint) from public;
revoke all on function public.spin_football_slots(uuid, bigint) from anon;
revoke all on function public.spin_football_slots(uuid, bigint) from authenticated;
grant execute on function public.spin_football_slots(uuid, bigint) to service_role;
